DRAWSCREEN:
#[
	//COPY 224x288 gameExportScreen TO FB
	LDR X10, =FB
	LDR X10, [X10]
		//SCREEN OFFSET
		ADD X10, X10, #1152		//X OFFSET
		ADD X10, X10, #307200	//Y OFFSET
	LDR X1, =COLORPAL
	LDR X2, =gameExportScreen
	
	
	MOV W7, #288	//TOTAL LINES
	COPYNEXTLINE:
		MOV W6, #224
	COPYTOFBLOOP:
		LDRB W3, [X2], #1	//GET PIXEL COLOR PALETTE INDEX
		LDR W4, [X1, X3, LSL #2]	//GET COLOR WORD
		STR W4, [X10], #4
		//REPEAT TO REDUCE BRANCHING
		LDRB W3, [X2], #1	//GET PIXEL COLOR PALETTE INDEX
		LDR W4, [X1, X3, LSL #2]	//GET COLOR WORD
		STR W4, [X10], #4
		
		LDRB W3, [X2], #1	//GET PIXEL COLOR PALETTE INDEX
		LDR W4, [X1, X3, LSL #2]	//GET COLOR WORD
		STR W4, [X10], #4
		
		LDRB W3, [X2], #1	//GET PIXEL COLOR PALETTE INDEX
		LDR W4, [X1, X3, LSL #2]	//GET COLOR WORD
		STR W4, [X10], #4
		AFTEREXPORTPIXEL:
		SUBS W6, W6, #4
		BNE COPYTOFBLOOP
		//ADD OFFSET TO X10
		ADD X10, X10, #2304
		SUBS W7, W7, #1
		BNE COPYNEXTLINE
		
	RET
	
#]

INITBUTTONPINS:
	#[
		//1, 4, 5, 6			GPFSEL0
		//12, 16, 17			GPFSEL1
		//22, 23, 24, 25, 27	GPFSEL2
		
		//SET GPIO 1, 4, 5, 6 FUNCTION AS INPUT (ALL 0)
		EOR X0, X0, X0
		LDR W0, =GPIO_BASE
		STR WZR, [X0, #GPFSEL0]
		STR WZR, [X0, #GPFSEL1]
		STR WZR, [X0, #GPFSEL2]
		DMB SY
		ISB
		//GPIO 1-8 DEFAULT TO PULL UP, MAKE PULL DOWN
		MOV W1, #0x1	//PULL DOWN
		STR W1, [X0, #GPPUD]	//SET PULL UP/DOWN CONTROL REGISTER
		//BURN 150 CYCLES
			MOV  X0, #150  
			BURN150L0:
				SUBS X0, X0, #1
				BNE  BURN150L0
		MOV W2, #0x72	//1, 4, 5, 6
		STR W2, [X0, #GPPUDCLK0]	//SET PIN VALUES
		//BURN 150 CYCLES
			MOV  X0, #150  
			BURN150L1:
				SUBS X0, X0, #1
				BNE  BURN150L1
		STR WZR, [X0, #GPPUD]
		STR WZR, [X0, #GPPUDCLK0]
		
		RET
	#]
	
	READALLBUTTONS:
	#[	//READ ALL 12 BUTTON STATUS
		LDR W2, [X0, #GPLEV0]	//READ ALL 32 GPIO STATUS
		//GET ADDRESS OF STATUS
		LDR X3, =BUTTONSTATUS
		//CHECK BITS 1, 4, 5, 6, 12, 16, 17, 22, 23, 24, 25, 27
		//BUTTON ORDER: 8, 9, 10, 0, 4, 5
		//				1, 6, 11, 7, 2, 3
		UBFX W1, W2, #1, #1
		STRB W1, [X3, #0]         //1
		UBFX W1, W2, #4, #1
		STRB W1, [X3, #1]         //4
		UBFX W1, W2, #5, #1
		STRB W1, [X3, #2]         //5
		UBFX W1, W2, #6, #1
		STRB W1, [X3, #3]         //6
		UBFX W1, W2, #12, #1
		STRB W1, [X3, #4]         //12
		UBFX W1, W2, #16, #1
		STRB W1, [X3, #5]         //16
		UBFX W1, W2, #17, #1
		STRB W1, [X3, #6]         //17
		UBFX W1, W2, #22, #1
		STRB W1, [X3, #7]         //22
		UBFX W1, W2, #23, #1
		STRB W1, [X3, #8]         //23
		UBFX W1, W2, #24, #1
		STRB W1, [X3, #9]         //24
		UBFX W1, W2, #25, #1
		STRB W1, [X3, #10]         //25
		UBFX W1, W2, #27, #1
		STRB W1, [X3, #11]         //27
		
		RET
	#]

CHECKBUTTONS:
#[
	STP X29, X30, [SP, #-16]!	//RETURN ADDRESS
	BL READALLBUTTONS
	LDR X3, =BUTTONSTATUS
	MOV W1, WZR
	
	CHECKRESET:
	LDRB W2, [X3, #4]
	CMP W2, #1
	BNE CHECKDOWNBUTTON
		//RESET
		BL initPACASM
		BL initZEROPAGE
		B ENDCHECKBUTTONS
	
	CHECKDOWNBUTTON:
	LDRB W2, [X3, #8]
	CMP W2, #1
	BNE CHECKUPBUTTON
		MOV W1, #8
		B ENDCHECKBUTTONS
	CHECKUPBUTTON:
	LDRB W2, [X3, #0]
	CMP W2, #1
	BNE CHECKLEFTBUTTON
		MOV W1, #4
		B ENDCHECKBUTTONS
	CHECKLEFTBUTTON:
	LDRB W2, [X3, #10]
	CMP W2, #1
	BNE CHECKRIGHTBUTTON
		MOV W1, #2
		B ENDCHECKBUTTONS
	CHECKRIGHTBUTTON:
	LDRB W2, [X3, #9]
	CMP W2, #1
	BNE ENDCHECKBUTTONS
		MOV W1, #1
	
	ENDCHECKBUTTONS:
	LDP X29, X30, [SP], #16
	RET
#]
