MAINCORELOOP:

	BL CHECKBUTTONS
	BL PACLOGIC
	BL PACGRAPHICS
	
	BL DRAWSCREEN	//drawScreen(offsetX, offsetY, maxScale);
	
	
	B MAINCORELOOP
	
